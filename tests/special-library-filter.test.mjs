import {test} from 'node:test';
import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';

test('Special filters find short Browser games, preserve records and remember the choice',async()=>{
 const dom=new JSDOM('<body></body>',{url:'https://test.local'}),{window}=dom;
 Object.assign(globalThis,{window,document:window.document,localStorage:window.localStorage});
 window.HTMLDialogElement.prototype.showModal=function(){this.open=true;};
 window.HTMLDialogElement.prototype.close=function(){this.open=false;this.dispatchEvent(new window.Event('close'));};
 const fen='8/8/8/8/8/8/8/K6k w - - 0 1';
 const records=[0,1,2,3,4].map(moves=>({id:String(moves),category:'imported',updatedAt:moves,json:JSON.stringify({board:fen,live_moves:Array(moves).fill('e4'),review_pgn:`[White "Player${moves}"]\n\n*`})}));
 const before=JSON.stringify(records);
 window.ironwoodCompanionFeatureEnabled=()=>false;
 globalThis.indexedDB=window.indexedDB={open(){const req={};queueMicrotask(()=>{req.result={transaction(){return {objectStore(){return {openCursor(){const cursor={};let index=0;const advance=()=>queueMicrotask(()=>{cursor.result=index<records.length?{value:records[index++],continue:advance}:null;cursor.onsuccess();});advance();return cursor;}};}};}};req.onsuccess();});return req;}};
 const {gameMatchesSpecialFilter}=await import('../web/game-storage.js?special-filter-test');
 assert.equal(gameMatchesSpecialFilter({moves:3},'short-games'),true);
 assert.equal(gameMatchesSpecialFilter({moves:4},'short-games'),false);
 assert.equal(gameMatchesSpecialFilter({},'short-games'),false);
 await window.ironwoodOpenGameLibrary();
 assert.equal(document.querySelectorAll('.game-library-entry').length,5);
 assert.equal(document.querySelector('.game-library-clear-filters').hidden,true);
 const select=document.querySelector('[aria-label="Special filters"]');
 select.value='short-games';select.dispatchEvent(new window.Event('change'));
 assert.equal(document.querySelectorAll('.game-library-entry').length,4);
 assert.doesNotMatch(document.querySelector('.game-library-list').textContent,/Player4/);
 document.querySelector('#game-library-dialog').close();await window.ironwoodOpenGameLibrary();
 assert.equal(document.querySelector('[aria-label="Special filters"]').value,'short-games');
 assert.equal(document.querySelectorAll('.game-library-entry').length,4);
 assert.equal(document.querySelector('.game-library-clear-filters').hidden,false);
 const actions=document.querySelector('.game-library-filter-actions');
 assert.equal(actions.children[0].className,'game-library-filter-section');
 assert.equal(actions.children[1].className,'game-library-clear-filters');
 const sorting=document.querySelector('[aria-label="Sort saved games"]');sorting.value='moves-asc';sorting.dispatchEvent(new window.Event('change'));
 document.querySelector('.game-library-clear-filters').click();
 assert.equal(document.querySelectorAll('.game-library-entry').length,5);
 assert.equal(document.querySelector('[aria-label="Special filters"]').value,'*');
 assert.equal(document.querySelector('[aria-label="Sort saved games"]').value,'moves-asc');
 assert.equal(document.querySelector('.game-library-clear-filters').hidden,true);
 assert.equal(JSON.stringify(records),before);
 document.querySelector('#game-library-dialog').close();
});
