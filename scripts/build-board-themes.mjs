import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const root = resolve(import.meta.dirname, '..');
const geometryFiles = ['board.glb', 'pawn.glb', 'rook.glb', 'knight.glb', 'bishop.glb', 'queen.glb', 'king.glb'];
export const boardThemeFiles = {
  wood: [...geometryFiles, 'pieces_white_diff.jpg', 'pieces_black_diff.jpg', 'board_diff.jpg', 'board_nor.jpg', 'board_rough.jpg', 'pieces_white_nor.jpg', 'pieces_black_nor.jpg'],
  marble: [...geometryFiles, 'chess_set_pieces_white_diff_1k.jpg', 'chess_set_pieces_black_diff_1k.jpg', 'chess_set_board_diff_1k.jpg', 'chess_set_board_nor_gl_1k.jpg', 'chess_set_board_arm_1k.jpg', 'chess_set_pieces_white_nor_gl_1k.jpg', 'chess_set_pieces_black_nor_gl_1k.jpg'],
};
export const boardThemeSources = { wood: 'omies-chess-set', marble: 'polyhaven-chess-set' };

// Preserve the existing CC0 source assets for native builds and provenance.
// Immutable browser copies share an identity across unrelated app updates.
export function buildBoardThemes({ sourceRoot = join(root, 'assets', '3d'), outputRoot = join(root, 'web', 'board-themes') } = {}) {
  const boardThemes = {};
  let bytes = 0;
  for (const [theme, files] of Object.entries(boardThemeFiles)) {
    boardThemes[theme] = {};
    for (const file of files) {
      const data = readFileSync(join(sourceRoot, boardThemeSources[theme], file));
      if (file.endsWith('.glb')) {
        if (data.length < 20 || data.toString('ascii', 0, 4) !== 'glTF' || data.readUInt32LE(4) !== 2 || data.readUInt32LE(8) !== data.length)
          throw new Error(`Invalid GLB: ${theme}/${file}`);
      } else if (data.length < 4 || data.readUInt16BE(0) !== 0xffd8 || data.readUInt16BE(data.length - 2) !== 0xffd9) {
        throw new Error(`Invalid JPEG: ${theme}/${file}`);
      }
      const hash = createHash('sha256').update(data).digest('hex');
      const relativePath = `${theme}/${hash}/${file}`;
      const destination = join(outputRoot, relativePath);
      mkdirSync(dirname(destination), { recursive: true });
      writeFileSync(destination, data);
      boardThemes[theme][file] = `/board-themes/${relativePath}`;
      bytes += data.length;
    }
  }
  writeFileSync(join(outputRoot, 'manifest.js'),
    `// Generated by scripts/build-board-themes.mjs from existing CC0 assets.\nexport const boardThemes = ${JSON.stringify(boardThemes, null, 2)};\n`);
  return { boardThemes, bytes };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const { bytes } = buildBoardThemes();
  console.log(`Prepared 2 optional 3D asset packs (${bytes.toLocaleString('en-US')} bytes).`);
}
