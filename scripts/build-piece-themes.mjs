import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const root = resolve(import.meta.dirname, '..');
export const themeNames = ['sculpted-marble', 'hybrid-wood', 'hybrid-glass'];
export const pieceNames = ['wK', 'wQ', 'wR', 'wB', 'wN', 'wP', 'bK', 'bQ', 'bR', 'bB', 'bN', 'bP'];

// Existing CC0 sprites remain the editable/native-build sources. Browser copies
// use immutable content paths so cached artwork survives unrelated app updates.
export function buildPieceThemes({ sourceRoot = join(root, 'web', 'pieces'), outputRoot = join(root, 'web', 'piece-themes') } = {}) {
  const pieceThemes = {};
  let bytes = 0;
  for (const theme of themeNames) {
    pieceThemes[theme] = {};
    for (const piece of pieceNames) {
      const image = readFileSync(join(sourceRoot, theme, `${piece}.png`));
      if (!image.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])))
        throw new Error(`Invalid PNG: ${theme}/${piece}.png`);
      const hash = createHash('sha256').update(image).digest('hex');
      const relativePath = `${theme}/${hash}/${piece}.png`;
      const destination = join(outputRoot, relativePath);
      mkdirSync(dirname(destination), { recursive: true });
      writeFileSync(destination, image);
      pieceThemes[theme][piece] = `/piece-themes/${relativePath}`;
      bytes += image.length;
    }
  }
  writeFileSync(join(outputRoot, 'manifest.js'),
    `// Generated by scripts/build-piece-themes.mjs from existing CC0 artwork.\nexport const pieceThemes = ${JSON.stringify(pieceThemes, null, 2)};\n`);
  return { pieceThemes, bytes };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const { bytes } = buildPieceThemes();
  console.log(`Prepared 3 optional piece themes (${bytes.toLocaleString('en-US')} bytes).`);
}
